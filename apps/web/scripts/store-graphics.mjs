// The pictures the stores ask for, drawn from the same mark the app draws (src/components/Logo.tsx),
// so the icon on the phone and the icon on the listing can never drift apart.
//
//   pnpm --filter @wusool/web store:graphics    → apps/web/store/
//
// Google Play wants a 512×512 icon and a 1024×500 feature graphic; Apple wants 1024×1024 with no
// transparency and no rounded corners of its own.
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const out = path.resolve(import.meta.dirname, '..', 'store');
mkdirSync(out, { recursive: true });

const NAVY = '#243283';
const YELLOW = '#F5B82E';

/** The mark itself: a smile under a sun. `rounded` is false where the store rounds it for us. */
const mark = (size, rounded) => `
<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 100 100">
  <rect width="100" height="100" rx="${rounded ? 26 : 0}" fill="${NAVY}"/>
  <path d="M26 49 A24 24 0 0 0 74 49" fill="none" stroke="#fff" stroke-width="11"
        stroke-linecap="round"/>
  <circle cx="50" cy="31" r="9" fill="${YELLOW}"/>
</svg>`;

/**
 * The feature graphic. Arabic first, because the app is Arabic first — and no promise on it:
 * what it says is what the app does, one tap at a time (clause 3 of the terms).
 */
const feature = `
<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="500" viewBox="0 0 1024 500">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#1B255F"/>
      <stop offset="1" stop-color="${NAVY}"/>
    </linearGradient>
  </defs>
  <rect width="1024" height="500" fill="url(#bg)"/>
  <g transform="translate(700 130) scale(2.4)">
    <rect width="100" height="100" rx="26" fill="#FFFFFF" fill-opacity="0.07"/>
    <path d="M26 49 A24 24 0 0 0 74 49" fill="none" stroke="#fff" stroke-width="11"
          stroke-linecap="round"/>
    <circle cx="50" cy="31" r="9" fill="${YELLOW}"/>
  </g>
  <text x="80" y="215" fill="#FFFFFF" font-size="96" font-weight="bold"
        font-family="Segoe UI, Tahoma, sans-serif">طمّني</text>
  <text x="80" y="290" fill="#FFFFFF" fill-opacity="0.82" font-size="33"
        font-family="Segoe UI, Tahoma, sans-serif">ضغطة عند الصعود، وضغطة عند النزول</text>
  <text x="80" y="352" fill="${YELLOW}" font-size="32"
        font-family="Segoe UI, Tahoma, sans-serif">Tammene</text>
</svg>`;

const files = [
  ['play-icon-512.png', mark(512, true), 512, 512],
  ['apple-icon-1024.png', mark(1024, false), 1024, 1024],
  ['play-feature-1024x500.png', feature, 1024, 500],
];

for (const [name, svg, w, h] of files) {
  await sharp(Buffer.from(svg))
    .resize(w, h)
    // Stores reject transparency on these, so they are flattened onto the brand colour.
    .flatten({ background: NAVY })
    .png()
    .toFile(path.join(out, name));
  console.log(`✓ store/${name}  ${w}×${h}`);
}

writeFileSync(
  path.join(out, 'README.md'),
  `# Store graphics

Generated by \`pnpm --filter @wusool/web store:graphics\` from the same mark the app draws
(\`src/components/Logo.tsx\`). Do not edit by hand — change the logo and run it again.

| File | Where it goes |
| ---- | ------------- |
| \`play-icon-512.png\` | Google Play → Store listing → App icon |
| \`play-feature-1024x500.png\` | Google Play → Store listing → Feature graphic |
| \`apple-icon-1024.png\` | App Store Connect → App icon |

Screenshots are not generated: they must show the real app, taken on a phone or the emulator
signed in as one of the test accounts (docs/DEMO.md), never a real child.
`,
);
console.log('✓ store/README.md');
