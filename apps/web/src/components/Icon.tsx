export type IconName = keyof typeof SOURCES;

const pathOf = (svg: string) => /\sd="([^"]+)"/.exec(svg)?.[1] ?? '';
const PATHS = Object.fromEntries(
  Object.entries(SOURCES).map(([name, [outline, fill]]) => [name, [pathOf(outline), pathOf(fill)]]),
) as Record<IconName, [string, string]>;

/**
 * Decorative by default. Give it a `label` when the icon is the only thing that says what it
 * means; colour is never the only signal (PLAN §15).
 */
export function Icon({
  name,
  fill = false,
  size = 22,
  label,
  flip = false,
  className,
}: {
  name: IconName;
  fill?: boolean;
  size?: number;
  label?: string;
  /** Mirror the icon in that writing direction (arrows and chevrons). */
  flip?: 'rtl' | 'ltr' | false;
  className?: string;
}) {
  return (
    <svg
      viewBox="0 -960 960 960"
      width={size}
      height={size}
      fill="currentColor"
      role={label ? 'img' : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      className={cn(
        'shrink-0',
        flip === 'rtl' && 'rtl:-scale-x-100',
        flip === 'ltr' && 'ltr:-scale-x-100',
        className,
      )}
    >
      <path d={PATHS[name][fill ? 1 : 0]} />
    </svg>
  );
}
